using System.ComponentModel;
using System.Runtime.CompilerServices;

namespace Mdm.Services;

public class I18n : INotifyPropertyChanged
{
    public static I18n Instance { get; } = new();

    public event PropertyChangedEventHandler? PropertyChanged;
    public event EventHandler<string>? LanguageChanged;

    public string CurrentLanguage { get; private set; } = "id";

    public string this[string key] => Tr(key);

    public void Initialize(Database? db = null)
    {
        if (db != null)
        {
            string lang = db.GetSetting("language", "id") ?? "id";
            SetLanguage(lang);
        }
    }

    public void SetLanguage(string lang)
    {
        string normalized = lang.ToLowerInvariant() switch
        {
            "en" or "english" => "en",
            _ => "id"
        };

        if (CurrentLanguage != normalized)
        {
            CurrentLanguage = normalized;
            PropertyChanged?.Invoke(this, new PropertyChangedEventArgs(string.Empty));
            PropertyChanged?.Invoke(this, new PropertyChangedEventArgs("Item[]"));
            PropertyChanged?.Invoke(this, new PropertyChangedEventArgs(nameof(CurrentLanguage)));
            LanguageChanged?.Invoke(this, CurrentLanguage);
        }
    }

    public static string Tr(string key, string? fallback = null)
    {
        return Instance.Translate(key, fallback);
    }

    public static string Format(string key, params object[] args)
    {
        string template = Tr(key);
        try
        {
            return string.Format(template, args);
        }
        catch
        {
            return template;
        }
    }

    public string Translate(string key, string? fallback = null)
    {
        if (string.IsNullOrEmpty(key)) return string.Empty;

        if (Translations.TryGetValue(CurrentLanguage, out var dict) && dict.TryGetValue(key, out var val))
        {
            return val;
        }

        // Fallback to default (id) if not found in current language
        if (CurrentLanguage != "id" && Translations.TryGetValue("id", out var idDict) && idDict.TryGetValue(key, out var idVal))
        {
            return idVal;
        }

        return fallback ?? key;
    }

